function a11y(title: string) {
  const decorative = title === "";
  return {
    role: decorative ? ("presentation" as const) : ("img" as const),
    "aria-hidden": decorative || undefined,
    "aria-label": decorative ? undefined : title,
    decorative,
  };
}

